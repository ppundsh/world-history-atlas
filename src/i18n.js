export function t(lang) { return S[lang] || S['zh-Hant']; }

export function formatYear(lang, y) {
  const s = t(lang);
  return y < 0 ? s.bc(-y) : s.ad(y === 0 ? 1 : y);
}

export function detectLang() {
  const saved = safeGet('lang');
  if (saved && S[saved]) return saved;
  const n = (navigator.language || 'zh-TW').toLowerCase();
  if (n.startsWith('zh')) return /cn|sg|hans/.test(n) ? 'zh-Hans' : 'zh-Hant';
  if (n.startsWith('ja')) return 'ja';
  if (n.startsWith('en')) return 'en';
  return 'zh-Hant';
}

