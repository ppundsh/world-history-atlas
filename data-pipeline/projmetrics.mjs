// Distortion metrics for every projection → src/projmetrics.gen.js (the hexagon chart in the menu).
// For ~6000 evenly spread points of the part of the globe each projection can show, the Tissot indicatrix
// (largest and smallest local scale a ≥ b) is measured by finite differences, then:
//   area      – how evenly areas are kept:        spread of ln(a·b)
//   shape     – how well angles / shapes are kept: mean angular distortion 2·asin((a−b)/(a+b))
//   distance  – how evenly lengths are kept:       spread of ln a and ln b
//   coverage  – share of the globe it can show
//   edges     – how bad it gets at the worst places: 95th percentile of the combined distortion
//   balance   – compromise between area and shape: high when neither is badly sacrificed
// Each score is 0…1 (1 = best). Run: node data-pipeline/projmetrics.mjs
import { writeFileSync } from 'node:fs';
import { geoDistance } from 'd3-geo';
import { PROJ } from '../src/projections.js';

const N = 6000, R = Math.PI / 180;
const pts = [];
for (let i = 0; i < N; i++) {            // Fibonacci sphere
  const z = 1 - (2 * i + 1) / N, r = Math.sqrt(1 - z * z), t = i * Math.PI * (3 - Math.sqrt(5));
  pts.push([Math.atan2(r * Math.sin(t), r * Math.cos(t)) / R, Math.asin(z) / R]);
}
const median = a => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const out = {};
for (const [id, def] of Object.entries(PROJ)) {
  if (id === 'globe') { out[id] = { area: 1, shape: 1, distance: 1, coverage: 0.5, edges: 1, balance: 1 }; continue; }
  const p = def.make(); if (def.clip) p.clipAngle(def.clip);
  p.rotate([0, 0]).scale(1).translate([0, 0]);
  const inside = ([lon, lat]) => {
    if (def.clip && geoDistance([lon, lat], [0, 0]) > def.clip * R * 0.98) return false;
    if (def.lat && (lat < def.lat[0] || lat > def.lat[1])) return false;
    return Math.abs(lat) < 89 && Math.abs(lon) < 179.5;
  };
  const la = [], lb = [], om = [];
  let shown = 0;
  const h = 0.01;
  for (const q of pts) {
    if (!inside(q)) continue;
    const c = p(q), e = p([q[0] + h, q[1]]), n = p([q[0], q[1] + h]);
    if (!c || !e || !n || [...c, ...e, ...n].some(v => !isFinite(v))) continue;
    shown++;
    const k = 1 / (h * R), cl = Math.cos(q[1] * R);
    const xl = (e[0] - c[0]) * k / cl, yl = (e[1] - c[1]) * k / cl, xp = (n[0] - c[0]) * k, yp = (n[1] - c[1]) * k;
    // singular values of the Jacobian [[xl, xp], [yl, yp]]
    const E = (xl * xl + yl * yl + xp * xp + yp * yp) / 2, D = Math.abs(xl * yp - xp * yl);
    const s = Math.sqrt(Math.max(0, E * E - D * D));
    const a = Math.sqrt(E + s), b = Math.sqrt(Math.max(1e-12, E - s));
    la.push(Math.log(a)); lb.push(Math.log(b)); om.push(2 * Math.asin((a - b) / (a + b)));
  }
  const lab = la.map((x, i) => x + lb[i]), mab = median(lab), m = median([...la, ...lb]);
  const areaDev = lab.reduce((s, x) => s + Math.abs(x - mab), 0) / lab.length;
  const omega = om.reduce((s, x) => s + x, 0) / om.length;
  const distDev = la.reduce((s, x, i) => s + (Math.abs(x - m) + Math.abs(lb[i] - m)) / 2, 0) / la.length;
  const comb = la.map((x, i) => Math.abs(x - lb[i]) + Math.abs(lab[i] - mab)).sort((x, y) => x - y);
  const p95 = comb[Math.floor(comb.length * 0.95)];
  const area = 1 / (1 + 2.5 * areaDev), shape = 1 / (1 + 3 * omega), distance = 1 / (1 + 2.5 * distDev);
  out[id] = {
    area, shape, distance,
    coverage: shown / N,
    edges: 1 / (1 + 1.2 * p95),
    balance: 2 * Math.min(area, shape) / (area + shape) * Math.sqrt(area * shape),
  };
}
for (const v of Object.values(out)) for (const k in v) v[k] = Math.round(v[k] * 100) / 100;
writeFileSync(new URL('../src/projmetrics.gen.js', import.meta.url),
  '// generated by data-pipeline/projmetrics.mjs — distortion scores 0…1 (1 = best)\nexport const PROJ_METRICS = ' + JSON.stringify(out, null, 0).replace(/},"/g, '},\n"') + ';\n');
console.table(out);
