// projinfo.tsv → src/projinfo.gen.js (projection descriptions; zh-Hans converted from zh-Hant, descriptive text only)
import { readFileSync, writeFileSync } from 'node:fs';
import * as OpenCC from 'opencc-js';
const tw2cn = OpenCC.Converter({ from: 'tw', to: 'cn' });
const here = new URL('.', import.meta.url);
const out = {};
for (const line of readFileSync(new URL('projinfo.tsv', here), 'utf8').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const [id, star, lang, use, pros, cons, design] = line.split('\t');
  const o = out[id] ||= { star: star === '1' };
  o[lang] = { use, pros, cons, design };
  if (lang === 'zh-Hant') o['zh-Hans'] = Object.fromEntries(Object.entries(o[lang]).map(([k, v]) => [k, tw2cn(v)]));
}
writeFileSync(new URL('../src/projinfo.gen.js', here),
  '// generated by data-pipeline/build_projinfo.mjs from projinfo.tsv — do not edit\nexport const PROJ_INFO = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('projinfo:', Object.keys(out).length, 'projections');
