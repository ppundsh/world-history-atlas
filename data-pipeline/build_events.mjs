// events_world.tsv → src/worldEvents.gen.js (timeline events of the world), and events_<mode>.tsv → the own events of
// the global modes without a data file of their own (religion, regime, art), shown even with the world's events off
// Names are written per language; descriptions in zh-Hans are converted from zh-Hant (prose only).
import { readFileSync, writeFileSync } from 'node:fs';
import * as OpenCC from 'opencc-js';
const tw2cn = OpenCC.Converter({ from: 'tw', to: 'cn' });
const here = new URL('.', import.meta.url);
function read(file) {
  const out = [];
  for (const line of readFileSync(new URL(file, here), 'utf8').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const f = line.split('\t');
    if (f.length < 13) throw new Error(file + ': 13 columns expected: ' + line.slice(0, 40));
    const [y, e, big, hant, hans, en, ja, wzh, wen, wja, dhant, den, dja, lon, lat] = f;
    out.push({ y: +y, ...(e ? { e: +e } : {}), ...(big === '1' ? { big: true } : {}),
      n: [hant, hans, en, ja], w: [wzh, wen, wja], d: [dhant, tw2cn(dhant), den, dja], ...(lon && lat ? { lon: +lon, lat: +lat } : {}) });
  }
  return out.sort((a, b) => a.y - b.y);
}
const out = read('events_world.tsv');
const modes = Object.fromEntries(['religion', 'regime', 'art'].map(m => [m, read('events_' + m + '.tsv')]));
const js = x => JSON.stringify(x, null, 0).replace(/},{/g, '},\n{');
writeFileSync(new URL('../src/worldEvents.gen.js', here),
  '// generated by data-pipeline/build_events.mjs from events_world.tsv and events_<mode>.tsv — do not edit\n// n/d: [zh-Hant, zh-Hans, en, ja] (main.js reorders to LANGS.col); w: Wikipedia articles [zh, en, ja]\nexport const WORLD_EVENTS = ' + js(out) + ';\n' +
  '// the own events of the religion, regime and art modes\nexport const MODE_EVENTS = ' + js(modes) + ';\n');
console.log('events:', out.length, Object.entries(modes).map(([k, v]) => k + ' ' + v.length).join(', '));
