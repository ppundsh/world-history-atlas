// events_world.tsv → src/worldEvents.gen.js (timeline events of the world and religion modes)
// Names are written per language; descriptions in zh-Hans are converted from zh-Hant (prose only).
import { readFileSync, writeFileSync } from 'node:fs';
import * as OpenCC from 'opencc-js';
const tw2cn = OpenCC.Converter({ from: 'tw', to: 'cn' });
const here = new URL('.', import.meta.url);
const out = [];
for (const line of readFileSync(new URL('events_world.tsv', here), 'utf8').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  const f = line.split('\t');
  if (f.length < 13) throw new Error('events_world.tsv: 13 columns expected: ' + line.slice(0, 40));
  const [y, e, big, hant, hans, en, ja, wzh, wen, wja, dhant, den, dja] = f;
  out.push({ y: +y, ...(e ? { e: +e } : {}), ...(big === '1' ? { big: true } : {}),
    n: [hant, hans, en, ja], w: [wzh, wen, wja], d: [dhant, tw2cn(dhant), den, dja] });
}
writeFileSync(new URL('../src/worldEvents.gen.js', here),
  '// generated by data-pipeline/build_events.mjs from events_world.tsv — do not edit\n// n/d: [zh-Hant, zh-Hans, en, ja] (main.js reorders to LANGS.col); w: Wikipedia articles [zh, en, ja]\nexport const WORLD_EVENTS = ' + JSON.stringify(out, null, 0).replace(/},{/g, '},\n{') + ';\n');
console.log('events:', out.length);
